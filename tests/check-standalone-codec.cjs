const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/../build/hongguo-standalone/service/provider.js','utf8');
const selector=source.match(/function (?:ue|ae)\(e,t,r\)\{var n=String\(t\|\|""\)\.toUpperCase\(\);.*?\}(?=function (?:le|se))/s);
assert(selector,'upstream quality selector was not found');
const choose=vm.runInNewContext('('+selector[0]+')',{I:(message)=>new Error(message)});
const hevc={codec:'bytevc1',quality:'720P',height:720},avc={codec:'h264',quality:'540P',height:540};
assert.equal(choose([hevc,avc],'',true).codec,'h264');
assert.equal(choose([hevc],'',true).codec,'bytevc1');
assert.equal(choose([avc],'720P',true).quality,'540P');
assert.throws(()=>choose([avc],'720P',false));
const hevc1080={codec:'h265',quality:'1080P',height:1080};
assert.strictEqual(choose([hevc1080,avc],'1080P',false),hevc1080,'explicit available quality must not silently downgrade for codec preference');
assert.strictEqual(choose([hevc1080,avc],'1080P',true),hevc1080,'fallback permission must not downgrade an available requested quality');
assert.strictEqual(choose([hevc1080,avc],'AUTO',true),avc,'automatic quality should prefer compatible AVC');
const keyFunction=source.match(/function (?:le|se)\(e,t,n,i,o\)\{.*?\}(?=function (?:de|ce))/s);
assert(keyFunction,'upstream media cache identity function was not found');
const crypto=require('crypto'),cacheKey=vm.runInNewContext('('+keyFunction[0]+')',{r:crypto});
const legacyKey=crypto.createHash('sha256').update('series:video').digest('hex').slice(0,24);
assert.notEqual(cacheKey('series','video','',true,'full'),legacyKey);
assert.notEqual(cacheKey('series','video','',true,'range'),cacheKey('series','video','',true,'full'));
assert.notEqual(cacheKey('series','video','1080P',true,'range'),cacheKey('series','video','540P',true,'range'));
console.log('PASS: AVC auto preference, explicit HEVC quality preservation, quality fallback, strict quality, separate cache identities');
